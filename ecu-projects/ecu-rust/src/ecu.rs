pub fn handle_request(session: &mut u8, req: &[u8]) -> Vec<u8> {
    match req {
        [0x10, 0x01] => {
            *session = 0x01;
            vec![0x50, 0x01]
        }
        [0x10, 0x03] => {
            *session = 0x03;
            vec![0x50, 0x03]
        }
        [0x10, _] => vec![0x7F, 0x10, 0x12],
        [0x10, ..] => vec![0x7F, 0x10, 0x13],

        [0x22, 0xF1, 0x90] if *session == 0x03 => {
            vec![0x62, 0xF1, 0x90, 0x01, 0x02, 0x03, 0x04]
        }
        [0x22, _, _] if *session != 0x03 => vec![0x7F, 0x22, 0x7F],
        [0x22, _, _] => vec![0x7F, 0x22, 0x31],
        [0x22, ..] => vec![0x7F, 0x22, 0x13],

        [sid, ..] => vec![0x7F, *sid, 0x11],
        [] => vec![],
    }
}
